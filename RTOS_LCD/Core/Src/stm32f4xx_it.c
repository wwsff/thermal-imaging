/**
  * @brief This function handles Hard fault interrupt.
  */
void HardFault_Handler(void)
{
  /* USER CODE BEGIN HardFault_IRQn 0 */
  uint32_t *fault_frame;
  uint32_t frame_offset;

  g_hardfault_cfsr = SCB->CFSR;
  g_hardfault_hfsr = SCB->HFSR;
  g_hardfault_dfsr = SCB->DFSR;
  g_hardfault_afsr = SCB->AFSR;
  g_hardfault_mmfar = SCB->MMFAR;
  g_hardfault_bfar = SCB->BFAR;
  g_hardfault_psp = __get_PSP();
  g_hardfault_msp = __get_MSP();

  /* RTOS任务使用PSP；FPU上下文存在时，核心寄存器帧位于其后18个word。 */
  frame_offset = ((__get_CONTROL() & (1UL << 2)) != 0U) ? 18U : 0U;
  fault_frame = (uint32_t *)(g_hardfault_psp + frame_offset * sizeof(uint32_t));
  if (((uint32_t)fault_frame >= 0x20000000UL) &&
      ((uint32_t)fault_frame <= 0x2001FFE0UL))
  {
    g_hardfault_stacked_lr = fault_frame[5];
    g_hardfault_stacked_pc = fault_frame[6];
    g_hardfault_stacked_xpsr = fault_frame[7];
  }
  /* USER CODE END HardFault_IRQn 0 */
  while (1)
  {
    /* USER CODE BEGIN W1_HardFault_IRQn 0 */
    /* USER CODE END W1_HardFault_IRQn 0 */
  }
}

